#!/bin/sh
# Builds the résumé designs from content.html + base.css + a stylesheet.
#   style.css   -> resume.html   -> projects/Resume_parkseoyoon_2026.pdf
# Run from anywhere:  resume/build.sh
CHROME="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
cd "$(dirname "$0")" || exit 1
build() {  # build <stylesheet> <html> <pdf>
    {
        printf '<!doctype html>\n<!-- generated by build.sh: edit content.html or %s instead -->\n<html lang="en"><head><meta charset="UTF-8"><title>Seoyoon Park | Résumé</title>\n<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&display=swap" rel="stylesheet">\n<style>\n' "$1"
        cat base.css "$1"
        printf '</style></head><body>\n'
        cat content.html
        printf '</body></html>\n'
    } > "$2"
    "$CHROME" --headless --no-pdf-header-footer --virtual-time-budget=5000 --print-to-pdf="../projects/$3" "$2" 2>/dev/null
}
build style.css   resume.html   Resume_parkseoyoon_2026.pdf
